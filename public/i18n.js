window.getBingoLang = function () {
  try {
    var l = localStorage.getItem("bingoLang");
    if (l === "en" || l === "am") return l;
  } catch (_) {}
  return "am";
};

window.t = function (key, fallback) {
  var lang = window.getBingoLang();
  var pack = (window.BINGO_I18N && window.BINGO_I18N[lang]) || {};
  var en = (window.BINGO_I18N && window.BINGO_I18N.en) || {};
  if (pack[key] != null) return pack[key];
  if (en[key] != null) return en[key];
  return fallback != null ? fallback : key;
};

window.applyBingoLanguage = function (language, persist) {
  var lang = language === "en" ? "en" : "am";
  if (persist !== false) {
    try { localStorage.setItem("bingoLang", lang); } catch (_) {}
  }
  var pack = (window.BINGO_I18N && window.BINGO_I18N[lang]) || {};
  document.querySelectorAll("[data-i18n]").forEach(function (el) {
    var key = el.getAttribute("data-i18n");
    if (pack[key] != null) el.textContent = pack[key];
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
    var key = el.getAttribute("data-i18n-placeholder");
    if (pack[key] != null) el.setAttribute("placeholder", pack[key]);
  });
  document.documentElement.setAttribute("lang", lang === "am" ? "am" : "en");
  var sel = document.getElementById("languageSelect");
  if (sel) sel.value = lang;
};
